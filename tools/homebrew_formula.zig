//! Writes the Homebrew formula of a release, which the release workflow commits to the tap
//! jinzhongjia/homebrew-tap.
//!
//! Usage: zig build homebrew-formula -- <tag> <SHA256SUMS of the release> <output file>
//!
//! The formula installs the ReleaseSafe archives of macOS and Linux (x86_64 and aarch64). The
//! executable and its `.dSYM` bundle go into libexec with a symlink in bin: std.debug looks for the
//! debug information next to the executable after resolving symlinks.

const std = @import("std");
const Io = std.Io;
const Allocator = std.mem.Allocator;

const repo_url = "https://github.com/jinzhongjia/zig-analyzer";

/// The archives of the formula, by the `on_*` blocks that select them
const platforms = [_]struct { os: []const u8, cpu: []const u8, target: []const u8 }{
    .{ .os = "macos", .cpu = "arm", .target = "aarch64-macos" },
    .{ .os = "macos", .cpu = "intel", .target = "x86_64-macos" },
    .{ .os = "linux", .cpu = "arm", .target = "aarch64-linux" },
    .{ .os = "linux", .cpu = "intel", .target = "x86_64-linux" },
};

pub fn main(init: std.process.Init) !u8 {
    const io = init.io;
    const arena = init.arena.allocator();
    const args = try init.minimal.args.toSlice(arena);
    if (args.len != 4) {
        std.debug.print("usage: {s} <tag> <SHA256SUMS> <output file>\n", .{args[0]});
        return 2;
    }
    const sums = try Io.Dir.cwd().readFileAlloc(io, args[2], arena, .unlimited);
    var out: Io.Writer.Allocating = .init(arena);
    formula(&out.writer, args[1], sums) catch |err| switch (err) {
        error.MissingArchive => {
            std.debug.print("error: {s} lacks a ReleaseSafe archive of {s}\n", .{ args[2], args[1] });
            return 1;
        },
        else => |e| return e,
    };
    try Io.Dir.cwd().writeFile(io, .{ .sub_path = args[3], .data = out.written() });
    return 0;
}

/// The formula of the release `tag`, whose archives have the checksums listed in `sums` (the
/// output of `sha256sum`)
fn formula(w: *Io.Writer, tag: []const u8, sums: []const u8) (Io.Writer.Error || error{MissingArchive})!void {
    try w.writeAll(
        \\# Generated by tools/homebrew_formula.zig in jinzhongjia/zig-analyzer for each release.
        \\class ZigAnalyzer < Formula
        \\  desc "Zig language server with compiler diagnostics and comptime-aware analysis"
        \\
    );
    try w.print("  homepage \"{s}\"\n", .{repo_url});
    try w.writeAll(
        \\  license "MIT"
        \\
        \\  livecheck do
        \\    url :stable
        \\    strategy :github_latest
        \\  end
        \\
    );
    for (platforms, 0..) |p, i| {
        const first_of_os = i == 0 or !std.mem.eql(u8, platforms[i - 1].os, p.os);
        const last_of_os = i + 1 == platforms.len or !std.mem.eql(u8, platforms[i + 1].os, p.os);
        if (first_of_os) try w.print("\n  on_{s} do\n", .{p.os});
        try w.print(
            \\    on_{s} do
            \\      url "{s}/releases/download/{s}/zig-analyzer-{s}-{s}-ReleaseSafe.tar.gz"
            \\      sha256 "{s}"
            \\    end
            \\
        , .{ p.cpu, repo_url, tag, tag, p.target, checksum(sums, tag, p.target) orelse return error.MissingArchive });
        if (last_of_os) try w.writeAll("  end\n");
    }
    try w.writeAll(
        \\
        \\  def install
        \\    libexec.install "zig-analyzer"
        \\    libexec.install "zig-analyzer.dSYM" if OS.mac?
        \\    bin.install_symlink libexec/"zig-analyzer"
        \\  end
        \\
        \\  def caveats
        \\    <<~EOS
        \\      zig-analyzer runs the Zig compiler for diagnostics and needs Zig 0.17.0 or 0.17.1
        \\      in PATH, or its path in the zig.path setting.
        \\    EOS
        \\  end
        \\
        \\  test do
        \\    assert_equal version.to_s, shell_output("#{bin}/zig-analyzer --version").strip
        \\  end
        \\end
        \\
    );
}

/// The checksum of the ReleaseSafe archive of `target` in the output of `sha256sum` (`<hash>  <name>`,
/// or `<hash> *<name>` for binary mode)
fn checksum(sums: []const u8, tag: []const u8, target: []const u8) ?[]const u8 {
    var lines = std.mem.splitScalar(u8, sums, '\n');
    while (lines.next()) |line| {
        const trimmed = std.mem.trimEnd(u8, line, "\r");
        if (trimmed.len < 66 or trimmed[64] != ' ') continue;
        const file = if (trimmed[65] == ' ' or trimmed[65] == '*') trimmed[66..] else continue;
        var rest = std.mem.cutPrefix(u8, file, "zig-analyzer-") orelse continue;
        rest = std.mem.cutPrefix(u8, rest, tag) orelse continue;
        rest = std.mem.cutPrefix(u8, rest, "-") orelse continue;
        rest = std.mem.cutPrefix(u8, rest, target) orelse continue;
        if (std.mem.eql(u8, rest, "-ReleaseSafe.tar.gz")) return trimmed[0..64];
    }
    return null;
}

