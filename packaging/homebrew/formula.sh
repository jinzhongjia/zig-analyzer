#!/usr/bin/env bash
# Prints the Homebrew formula of a release: formula.sh <tag> <SHA256SUMS of the release>
# The formula installs the ReleaseSafe archives of macOS and Linux (x86_64 and aarch64), and is
# published in the tap jinzhongjia/homebrew-tap by the release workflow.
set -euo pipefail

if [ $# -ne 2 ]; then
  echo "usage: $0 <tag> <SHA256SUMS>" >&2
  exit 2
fi
tag=$1
sums=$2
base="https://github.com/jinzhongjia/zig-analyzer/releases/download/$tag"

# The url and sha256 lines of the ReleaseSafe archive of the target $1; exits when SHA256SUMS lacks it
archive() {
  local name="zig-analyzer-$tag-$1-ReleaseSafe.tar.gz"
  local sum
  sum=$(awk -v n="$name" '$2 == n || $2 == "*" n { print $1 }' "$sums")
  if [ -z "$sum" ]; then
    echo "$sums lists no $name" >&2
    exit 1
  fi
  printf '      url "%s/%s"\n      sha256 "%s"' "$base" "$name" "$sum"
}
macos_arm=$(archive aarch64-macos)
macos_intel=$(archive x86_64-macos)
linux_arm=$(archive aarch64-linux)
linux_intel=$(archive x86_64-linux)

cat <<EOF
# Generated by packaging/homebrew/formula.sh in jinzhongjia/zig-analyzer for each release.
class ZigAnalyzer < Formula
  desc "Zig language server with compiler diagnostics and comptime-aware analysis"
  homepage "https://github.com/jinzhongjia/zig-analyzer"
  license "MIT"

  livecheck do
    url :stable
    strategy :github_latest
  end

  on_macos do
    on_arm do
$macos_arm
    end
    on_intel do
$macos_intel
    end
  end

  on_linux do
    on_arm do
$linux_arm
    end
    on_intel do
$linux_intel
    end
  end

  def install
    # The debug information of stack traces is read next to the executable, after resolving
    # symlinks: both go into libexec, which holds no other executables
    libexec.install "zig-analyzer"
    libexec.install "zig-analyzer.dSYM" if OS.mac?
    bin.install_symlink libexec/"zig-analyzer"
  end

  def caveats
    <<~EOS
      zig-analyzer runs the Zig compiler for diagnostics and needs Zig 0.17.0 or 0.17.1
      in PATH, or its path in the zig.path setting.
    EOS
  end

  test do
    assert_equal version.to_s, shell_output("#{bin}/zig-analyzer --version").strip
  end
end
EOF
