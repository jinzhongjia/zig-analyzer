const std = @import("std");
const testing = std.testing;
const naming = @import("naming.zig");
const resolve = @import("../names/resolve.zig");
const World = @import("../names/resolve_test.zig").World;

fn expectConvert(name: []const u8, style: naming.Style, expected: ?[]const u8) !void {
    var arena: std.heap.ArenaAllocator = .init(testing.allocator);
    defer arena.deinit();
    const got = try naming.convert(arena.allocator(), name, style);
    if (expected) |e| {
        try testing.expectEqualStrings(e, got orelse return error.TestExpectedConversion);
    } else if (got) |g| {
        std.debug.print("expected no conversion of `{s}`, got `{s}`\n", .{ name, g });
        return error.TestUnexpectedConversion;
    }
}

test "convert names between styles" {
    try expectConvert("packet_type", .title_case, "PacketType");
    try expectConvert("MakePacket", .camel_case, "makePacket");
    try expectConvert("packetFactory", .title_case, "PacketFactory");
    try expectConvert("localValue", .snake_case, "local_value");
    try expectConvert("x", .title_case, "X");
    // 缩写与首字母缩写按普通单词处理
    try expectConvert("XMLParser", .title_case, "XmlParser");
    try expectConvert("parseXML", .camel_case, "parseXml");
    try expectConvert("HTTPServer", .snake_case, "http_server");
    try expectConvert("UTF8String", .camel_case, "utf8String");
    try expectConvert("IPhone", .snake_case, "i_phone");
    try expectConvert("withoutIPIndex", .camel_case, "withoutIpIndex");
    try expectConvert("LMSPrimeToLab", .snake_case, "lms_prime_to_lab");
    // 数字归入前一个单词
    try expectConvert("readU32Be", .snake_case, "read_u32_be");
    try expectConvert("read_u32_be", .camel_case, "readU32Be");
    try expectConvert("vec3d", .title_case, "Vec3d");
    // 已符合的名字不变
    try expectConvert("XmlParser", .title_case, "XmlParser");
    try expectConvert("readU32Be", .camel_case, "readU32Be");
    try expectConvert("local_value", .snake_case, "local_value");
}

test "names whose words are unclear are not converted" {
    // 没有小写字母：可能是沿用外部的既有惯例
    try expectConvert("ENOENT", .snake_case, null);
    try expectConvert("MAX_SIZE", .snake_case, null);
    try expectConvert("T", .snake_case, null);
    // `_` 的前缀、后缀与连续的 `_`
    try expectConvert("_private", .snake_case, null);
    try expectConvert("type_", .title_case, null);
    try expectConvert("a__b", .camel_case, null);
    // 从连续的大写字母中分出的单词太短：缩写在哪里结束无法判断
    try expectConvert("URLs", .snake_case, null);
    try expectConvert("parseIDsFirst", .snake_case, null);
    try expectConvert("toHSLuv", .camel_case, null);
    try expectConvert("fromCIELChuv", .camel_case, null);
    try expectConvert("XYZAtoLMS", .snake_case, null);
    try expectConvert("CIExyY", .title_case, null);
    try expectConvert("URLPath", .snake_case, null);
    // 数字之后的单个大写字母
    try expectConvert("Vec3D", .snake_case, null);
    try expectConvert("readU32BE", .snake_case, null);
    // 只能以 `@"..."` 写出的名字
    try expectConvert("a b", .snake_case, null);
    try expectConvert("3d", .snake_case, null);
}

test "glob patterns" {
    try testing.expect(naming.globMatch("ENOENT", "ENOENT"));
    try testing.expect(!naming.globMatch("ENOENT", "ENOENTX"));
    try testing.expect(naming.globMatch("SDL_*", "SDL_Window"));
    try testing.expect(naming.globMatch("*_t", "size_t"));
    try testing.expect(!naming.globMatch("*_t", "size_type"));
    try testing.expect(naming.globMatch("src/*/types.zig", "src/lsp/types.zig"));
    try testing.expect(naming.globMatch("src/*", "src/a/b/c.zig"));
    try testing.expect(naming.globMatch("*a*b", "xaybab"));
    try testing.expect(naming.globMatch("*", ""));
    try testing.expect(!naming.globMatch("a*", "b"));
}

test "generated files are recognized by their leading comments" {
    try testing.expect(naming.isGenerated("// Code generated by gen.zig. DO NOT EDIT.\nconst x = 1;\n"));
    try testing.expect(naming.isGenerated("//! This file is auto-generated.\n"));
    try testing.expect(naming.isGenerated("// SPDX-License-Identifier: MIT\n// @generated\n"));
    try testing.expect(!naming.isGenerated("//! Packet parsing.\nconst x = 1;\n"));
    // 只看文件开头的注释
    try testing.expect(!naming.isGenerated("const x = 1;\n// generated by hand\n"));
}

/// fixture 中第一个文件的结果：每行「名字 -> 建议 (规则)」
fn expectFindings(fixture: []const u8, expected: []const u8) !void {
    var w: World = undefined;
    try w.init();
    defer w.deinit();
    const f = try w.fixture(fixture);
    const a = w.arena.allocator();
    var ctx = w.db.beginRead(a);
    defer ctx.end();
    var r: resolve.Resolver = .{ .ctx = &ctx, .arena = a };
    var out: std.ArrayList(u8) = .empty;
    for (try naming.findings(&r, f.files[0], null)) |x| try out.print(a, "{s} -> {s} ({t})\n", .{ x.name, x.suggestion, x.rule });
    try testing.expectEqualStrings(expected, out.items);
}

test "naming: types, callables and values by what they are" {
    try expectFindings(
        \\//- /p/main.zig
        \\const packet_type = struct { value: u32 };
        \\fn MakePacket() packet_type { return .{ .value = 1 }; }
        \\fn packetFactory(comptime T: type) type { return struct { value: T }; }
        \\const FactoryAlias = packetFactory;
        \\const Empty = struct {};
        \\pub fn main() void {
        \\    const localValue = MakePacket();
        \\    const marker: Empty = .{};
        \\    _ = localValue;
        \\    _ = marker;
        \\    _ = packetFactory(u32);
        \\    _ = FactoryAlias(u8);
        \\}
    ,
        \\packet_type -> PacketType (type)
        \\MakePacket -> makePacket (function)
        \\packetFactory -> PacketFactory (type_function)
        \\localValue -> local_value (value)
        \\
    );
}

test "naming: aliases and function pointers follow their targets" {
    try expectFindings(
        \\//- /p/main.zig
        \\fn functionName() void {}
        \\const FunctionAlias = functionName;
        \\const function_pointer: *const fn () void = &functionName;
        \\const StructName = struct { field: i32 };
        \\const struct_alias = StructName;
        \\const StructAlias = StructName;
        \\const PrimitiveTypeAlias = f32;
        \\const primitive_alias = f32;
        \\fn ListTemplateFunction(comptime ChildType: type, comptime fixed_size: usize) type {
        \\    return struct { items: [fixed_size]ChildType };
        \\}
        \\fn listOf(comptime T: type) type {
        \\    return []const T;
        \\}
        \\const make_list = listOf;
        \\const ListAlias = ListTemplateFunction;
    ,
        \\FunctionAlias -> functionAlias (function)
        \\function_pointer -> functionPointer (function)
        \\struct_alias -> StructAlias (type)
        \\primitive_alias -> PrimitiveAlias (type)
        \\listOf -> ListOf (type_function)
        \\make_list -> MakeList (type_function)
        \\
    );
}

