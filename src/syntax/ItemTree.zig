//! ItemTree: the declaration skeleton of a file.
//!
//! Records only "which containers exist, which members each container has, and each member's
//! name / kind / modifiers / signature hash / doc", with no position information and none of the
//! contents of function bodies or initializer expressions. Editing only a function body leaves
//! the ItemTree unchanged, so name resolution and signature type queries that depend on it are
//! not invalidated (early cutoff).
//!
//! Positions are looked up through `AstId` in `AstIdMap`. Containers defined inside function
//! bodies (such as the `struct {...}` returned by a generic type constructor) are included too,
//! since their members are part of name resolution.
//!
//! A ZON file has a single member: its root expression (kind `zon`, without a name), which owns
//! the Body that infers it.

const std = @import("std");
const Allocator = std.mem.Allocator;
const tree = @import("tree.zig");
const SyntaxNode = tree.SyntaxNode;
const SyntaxKind = @import("kind.zig").SyntaxKind;
const isTrivia = @import("kind.zig").isTrivia;
const ast = @import("ast.zig");
const Mode = @import("Parse.zig").Mode;

const ItemTree = @This();

arena: std.heap.ArenaAllocator.State,
/// Index 0 is the file itself
containers: []const Container,
items: []const Item,
/// Members of each container (indices into `items`), split by `Container.members`
member_list: []const u32,

/// Node ID stable within the file: hashed from the parent node ID, kind, name, and ordinal among
/// same-named nodes; stays the same across edits as long as the node is not renamed or moved.
pub const AstId = enum(u32) { _ };

pub const Container = struct {
    ast_id: AstId,
    kind: Kind,
    /// The member that lexically contains this container (null for the file root)
    parent_item: ?u32,
    members: struct { start: u32, len: u32 },
    /// `packed` / `extern` (layout and ABI size computations read it instead of the syntax tree)
    layout: Layout = .auto,
    /// `union(enum)`: the tag type is generated by the compiler
    auto_enum: bool = false,
    /// An enum with a `_` member: non-exhaustive. `_` is not a field and has no item
    nonexhaustive: bool = false,
    /// The container is what `parent_item` declares: the initializer of a `const` / `var` member,
    /// the type of a field, or the operand of a `return` in a function member's body. Other
    /// containers in a member (local types, call arguments, `?struct {...}`, parameter types) are
    /// only lexically inside it
    is_value: bool = false,
    /// The name of the declaration (a member or a local constant) whose initializer is the
    /// container; null for anonymous containers and the file root
    name: ?[]const u8 = null,

    pub const Kind = enum { file, @"struct", @"enum", @"union", @"opaque" };
    pub const Layout = enum { auto, @"packed", @"extern" };
};

pub const Item = struct {
    ast_id: AstId,
    kind: Kind,
    /// Tuple fields, comptime blocks, anonymous tests, and the root expression of a ZON file have
    /// no name
    name: ?[]const u8,
    container: u32,
    flags: Flags,
    /// Structural hash of the signature part: function prototype, variable type annotation and
    /// alignment etc., field type; excludes function bodies and initializer expressions
    sig_hash: u64,
    /// Doc comment text (with the `///` prefix removed), lines joined with `\n`
    doc: ?[]const u8,

    /// `zon`: the root expression of a ZON file. It is not a declaration: it takes no part in the
    /// outline, symbol search, naming checks, or name resolution
    pub const Kind = enum { @"fn", @"const", @"var", field, @"test", @"comptime", zon };

    pub const Flags = packed struct(u8) {
        is_pub: bool = false,
        is_extern: bool = false,
        is_export: bool = false,
        is_inline: bool = false,
        is_comptime: bool = false,
        is_threadlocal: bool = false,
        /// The function's return type is `!T` (inferred error set)
        inferred_error_set: bool = false,
        /// The function's parameter list has a non-binding parameter (`...`), only allowed last
        varargs: bool = false,
    };
};

pub fn deinit(self: *ItemTree, gpa: Allocator) void {
    var arena = self.arena.promote(gpa);
    arena.deinit();
    self.* = undefined;
}

/// A field may be just a name (enum members, void fields of unions), with the name in the
/// position of the type expression
pub fn bareFieldNames(kind: Container.Kind) bool {
    return kind == .@"enum" or kind == .@"union";
}

pub fn containerMembers(self: *const ItemTree, container: u32) []const u32 {
    const m = self.containers[container].members;
    return self.member_list[m.start..][0..m.len];
}

/// Whether the container declares a field; a file with top-level fields is a struct type, a file
/// without them is used as a namespace
pub fn hasFields(self: *const ItemTree, container: u32) bool {
    for (self.containerMembers(container)) |m| if (self.items[m].kind == .field) return true;
    return false;
}

pub fn eql(a: *const ItemTree, b: *const ItemTree) bool {
    if (a.containers.len != b.containers.len or a.items.len != b.items.len) return false;
    if (!std.mem.eql(u32, a.member_list, b.member_list)) return false;
    for (a.containers, b.containers) |x, y| {
        if (x.ast_id != y.ast_id or x.kind != y.kind or x.parent_item != y.parent_item) return false;
        if (x.layout != y.layout or x.auto_enum != y.auto_enum or x.nonexhaustive != y.nonexhaustive or x.is_value != y.is_value) return false;
        if (!optStrEql(x.name, y.name)) return false;
        if (x.members.start != y.members.start or x.members.len != y.members.len) return false;
    }
    for (a.items, b.items) |x, y| {
        if (x.ast_id != y.ast_id or x.kind != y.kind or x.container != y.container) return false;
        if (@as(u8, @bitCast(x.flags)) != @as(u8, @bitCast(y.flags)) or x.sig_hash != y.sig_hash) return false;
        if (!optStrEql(x.name, y.name) or !optStrEql(x.doc, y.doc)) return false;
    }
    return true;
}

fn optStrEql(a: ?[]const u8, b: ?[]const u8) bool {
    if (a == null or b == null) return a == null and b == null;
    return std.mem.eql(u8, a.?, b.?);
}

// ── Build ────────────────────────────────────────────────────────────

/// The root expression of a ZON file (the only child of the root node that is not an error node)
pub fn zonRoot(root: SyntaxNode) ?SyntaxNode {
    var it = root.children();
    while (it.nextNode()) |n| if (n.kind() != .error_node) return n;
    return null;
}

pub fn build(gpa: Allocator, root: SyntaxNode, mode: Mode) Allocator.Error!ItemTree {
    var arena: std.heap.ArenaAllocator = .init(gpa);
    errdefer arena.deinit();
    var b: Builder = .{ .gpa = gpa, .arena = arena.allocator() };
    defer b.deinit();

    const file_id = mixId(0, "file", "", 0);
    try b.taken.put(gpa, file_id, {});
    try b.containers.append(gpa, .{ .ast_id = file_id, .kind = .file, .parent_item = null, .members = undefined });
    switch (mode) {
        .zig => try b.visitContainer(root, 0),
        .zon => try b.visitZonRoot(root),
    }

    // Lay out the member lists in container order
    var member_list: std.ArrayList(u32) = .empty;
    for (b.containers.items, b.pending_members.items) |*c, members| {
        c.members = .{ .start = @intCast(member_list.items.len), .len = @intCast(members.items.len) };
        try member_list.appendSlice(b.arena, members.items);
    }
    const containers = try b.arena.dupe(Container, b.containers.items);
    const items = try b.arena.dupe(Item, b.items.items);
    return .{ .arena = arena.state, .containers = containers, .items = items, .member_list = member_list.items };
}

const Builder = struct {
    gpa: Allocator,
    arena: Allocator,
    containers: std.ArrayList(Container) = .empty,
    /// One-to-one with `containers`; collects each container's members during the build
    pending_members: std.ArrayList(std.ArrayList(u32)) = .empty,
    items: std.ArrayList(Item) = .empty,
    taken: std.AutoHashMapUnmanaged(AstId, void) = .empty,

    fn deinit(b: *Builder) void {
        b.containers.deinit(b.gpa);
        b.pending_members.deinit(b.gpa);
        b.items.deinit(b.gpa);
        b.taken.deinit(b.gpa);
    }

    /// `node` is a source_file or container_decl; `index` is its already registered container index
    fn visitContainer(b: *Builder, node: SyntaxNode, index: u32) Allocator.Error!void {
        while (b.pending_members.items.len <= index) try b.pending_members.append(b.gpa, .empty);
        const container_id = b.containers.items[index].ast_id;
        var it = node.children();
        while (it.nextNode()) |member| {
            const kind: Item.Kind = switch (member.kind()) {
                .fn_decl => .@"fn",
                .var_decl => if (member.childToken(.keyword_var) != null) .@"var" else .@"const",
                .container_field => if (isUnderscoreMarker(member, b.containers.items[index].kind)) {
                    b.containers.items[index].nonexhaustive = true;
                    continue;
                } else .field,
                .test_decl => .@"test",
                .comptime_decl => .@"comptime",
                else => continue,
            };
            const name = if (ast.memberName(member, bareFieldNames(b.containers.items[index].kind))) |t| try ast.identNameAlloc(b.arena, t.text) else null;
            const item_index: u32 = @intCast(b.items.items.len);
            try b.items.append(b.gpa, .{
                .ast_id = try b.uniqueId(container_id, @tagName(kind), name orelse ""),
                .kind = kind,
                .name = if (name) |n| try b.arena.dupe(u8, n) else null,
                .container = index,
                .flags = fnFlags(member, memberFlags(member)),
                .sig_hash = signatureHash(member, kind),
                .doc = try b.docText(member),
            });
            try b.pending_members.items[index].append(b.arena, item_index);
            try b.visitNested(member, item_index, valueOffset(member));
        }
    }

    /// A ZON file: the root expression is the only member of the file; container definitions inside
    /// it (not part of ZON, but parsable) are collected as usual
    fn visitZonRoot(b: *Builder, root: SyntaxNode) Allocator.Error!void {
        try b.pending_members.append(b.gpa, .empty);
        if (zonRoot(root) == null) return;
        const item_index: u32 = @intCast(b.items.items.len);
        try b.items.append(b.gpa, .{
            .ast_id = try b.uniqueId(b.containers.items[0].ast_id, "zon", ""),
            .kind = .zon,
            .name = null,
            .container = 0,
            .flags = .{},
            .sig_hash = 0,
            .doc = null,
        });
        try b.pending_members.items[0].append(b.arena, item_index);
        try b.visitNested(root, item_index, null);
    }

    /// Finds container definitions in a member's subtree (including inside function bodies),
    /// without descending into containers already found. `value` is the offset of the container
    /// that is the member's initializer or field type (see `valueOffset`)
    fn visitNested(b: *Builder, node: SyntaxNode, parent_item: u32, value: ?u32) Allocator.Error!void {
        var it = node.children();
        while (it.nextNode()) |c| {
            if (c.kind() != .container_decl) {
                try b.visitNested(c, parent_item, value);
                continue;
            }
            const index: u32 = @intCast(b.containers.items.len);
            const kind = containerKind(c);
            const bound = if (node.kind() == .var_decl) bound: {
                const decl: ast.VarDecl = .{ .syntax = node };
                const init = decl.initExpr() orelse break :bound null;
                if (init.offset != c.offset) break :bound null;
                const name = decl.name() orelse break :bound null;
                break :bound try b.arena.dupe(u8, try ast.identNameAlloc(b.arena, name.text));
            } else null;
            try b.containers.append(b.gpa, .{
                .ast_id = try b.uniqueId(b.items.items[parent_item].ast_id, "container", ""),
                .kind = kind,
                .parent_item = parent_item,
                .members = undefined,
                .layout = if (c.childToken(.keyword_packed) != null) .@"packed" else if (c.childToken(.keyword_extern) != null) .@"extern" else .auto,
                .auto_enum = kind == .@"union" and c.childToken(.keyword_enum) != null,
                .is_value = value == c.offset or (node.kind() == .return_expr and b.items.items[parent_item].kind == .@"fn"),
                .name = bound,
            });
            try b.visitContainer(c, index);
        }
    }

    /// Offset of the container that a member declares directly: the initializer of a `const` /
    /// `var` or the type of a field, when it is a container definition
    fn valueOffset(member: SyntaxNode) ?u32 {
        const value = switch (member.kind()) {
            .var_decl => (ast.VarDecl{ .syntax = member }).initExpr(),
            .container_field => (ast.ContainerField{ .syntax = member }).typeExpr(),
            else => null,
        } orelse return null;
        return if (value.kind() == .container_decl) value.offset else null;
    }

    /// The n-th node with the same (kind, name) under the same parent
    fn uniqueId(b: *Builder, parent: AstId, kind: []const u8, name: []const u8) Allocator.Error!AstId {
        var ordinal: u32 = 0;
        while (true) : (ordinal += 1) {
            const id = mixId(@backingInt(parent), kind, name, ordinal);
            if (!(try b.taken.getOrPut(b.gpa, id)).found_existing) return id;
        }
    }

    fn docText(b: *Builder, member: SyntaxNode) Allocator.Error!?[]const u8 {
        var out: std.ArrayList(u8) = .empty;
        var it = member.children();
        while (it.next()) |e| {
            if (e != .token) break;
            if (e.token.kind != .doc_comment) {
                if (isTrivia(e.token.kind)) continue;
                break;
            }
            var line = e.token.text["///".len..];
            if (std.mem.startsWith(u8, line, " ")) line = line[1..];
            if (out.items.len != 0) try out.append(b.arena, '\n');
            try out.appendSlice(b.arena, std.mem.trimEnd(u8, line, "\r"));
        }
        return if (out.items.len == 0) null else out.items;
    }
};

fn mixId(parent: u32, kind: []const u8, name: []const u8, ordinal: u32) AstId {
    var h: std.hash.Wyhash = .init(parent);
    h.update(kind);
    h.update(&.{0});
    h.update(name);
    h.update(std.mem.asBytes(&ordinal));
    return @fromBackingInt(@as(u32, @truncate(h.final())));
}

/// The bare `_` member of an enum, which marks it as non-exhaustive (`@"_"` is an ordinary field)
fn isUnderscoreMarker(member: SyntaxNode, container: Container.Kind) bool {
    if (container != .@"enum") return false;
    const name = ast.memberName(member, true) orelse return false;
    return std.mem.eql(u8, name.text, "_");
}

/// Syntactic information from the function prototype needed downstream (keeps signature
/// inference from reading the syntax tree, which changes on every edit)
fn fnFlags(member: SyntaxNode, base: Item.Flags) Item.Flags {
    var flags = base;
    const proto = (ast.cast(ast.FnDecl, member) orelse return flags).proto() orelse return flags;
    flags.inferred_error_set = proto.inferredErrorSet();
    var it = proto.params();
    while (it.next()) |p| {
        const param = ast.cast(ast.Param, p).?;
        if (param.name() == null and param.typeExpr() == null) flags.varargs = true;
    }
    return flags;
}

fn memberFlags(member: SyntaxNode) Item.Flags {
    var flags: Item.Flags = .{};
    var it = member.children();
    while (it.next()) |e| {
        if (e != .token) {
            if (e.node.kind() == .fn_proto) continue;
            break;
        }
        switch (e.token.kind) {
            .keyword_pub => flags.is_pub = true,
            .keyword_extern => flags.is_extern = true,
            .keyword_export => flags.is_export = true,
            .keyword_inline => flags.is_inline = true,
            .keyword_comptime => flags.is_comptime = true,
            .keyword_threadlocal => flags.is_threadlocal = true,
            .keyword_const, .keyword_var, .identifier, .keyword_fn => break,
            else => {},
        }
    }
    return flags;
}

fn containerKind(node: SyntaxNode) Container.Kind {
    var it = node.children();
    while (it.next()) |e| switch (e.kind()) {
        .keyword_struct => return .@"struct",
        .keyword_enum => return .@"enum",
        .keyword_union => return .@"union",
        .keyword_opaque => return .@"opaque",
        else => {},
    };
    return .@"struct";
}

/// Signature hash: hashes the non-trivia tokens (kind and text) of the signature part;
/// for a container definition only its head counts.
fn signatureHash(member: SyntaxNode, kind: Item.Kind) u64 {
    var h: std.hash.Wyhash = .init(0);
    switch (kind) {
        .@"fn" => if (member.childNode(.fn_proto)) |proto| hashTokens(&h, proto),
        .@"const", .@"var" => {
            // After the name and before `=`: type annotation and align / addrspace / linksection
            var it = member.children();
            var seen_name = false;
            while (it.next()) |e| {
                if (e == .token) {
                    if (e.token.kind == .equal) break;
                    if (e.token.kind == .identifier) seen_name = true;
                    if (seen_name and !isTrivia(e.token.kind)) hashToken(&h, e.token);
                } else if (seen_name) hashTokens(&h, e.node);
            }
            // When initialized with a container definition, include its head (kind, arguments);
            // the members are recorded separately
            if (initContainer(member)) |c| hashContainerHead(&h, c);
        },
        .field => {
            var it = member.children();
            while (it.next()) |e| {
                if (e == .token) {
                    if (e.token.kind == .equal) break;
                    if (!isTrivia(e.token.kind) and e.token.kind != .doc_comment) hashToken(&h, e.token);
                } else if (e.node.kind() == .container_decl) {
                    hashContainerHead(&h, e.node);
                } else hashTokens(&h, e.node);
            }
        },
        .@"test", .@"comptime", .zon => {},
    }
    return h.final();
}

fn initContainer(member: SyntaxNode) ?SyntaxNode {
    var it = member.children();
    var after_equal = false;
    while (it.next()) |e| {
        if (e == .token and e.token.kind == .equal) after_equal = true;
        if (after_equal and e == .node) return if (e.node.kind() == .container_decl) e.node else null;
    }
    return null;
}

fn hashContainerHead(h: *std.hash.Wyhash, node: SyntaxNode) void {
    var it = node.children();
    while (it.next()) |e| {
        if (e == .token) {
            if (e.token.kind == .l_brace) break;
            if (!isTrivia(e.token.kind)) hashToken(h, e.token);
        } else hashTokens(h, e.node);
    }
}

fn hashToken(h: *std.hash.Wyhash, t: tree.SyntaxToken) void {
    h.update(std.mem.asBytes(&t.kind));
    h.update(t.text);
}

fn hashTokens(h: *std.hash.Wyhash, node: SyntaxNode) void {
    var it = node.children();
    while (it.next()) |e| switch (e) {
        .token => |t| if (!isTrivia(t.kind)) hashToken(h, t),
        .node => |c| hashTokens(h, c),
    };
}

// ── AstId → node ─────────────────────────────────────────────────────

/// Mapping from AstId to node in one parse result. Rebuilt (cheaply) after every reparse; maps
/// stable IDs back to nodes in the current tree.
pub const AstIdMap = struct {
    map: std.AutoArrayHashMapUnmanaged(AstId, SyntaxNode) = .empty,

    pub fn deinit(m: *AstIdMap, gpa: Allocator) void {
        m.map.deinit(gpa);
    }

    /// Bytes used by the hash table (the nodes belong to the syntax tree and are not counted)
    pub fn bytes(m: *const AstIdMap) usize {
        return m.map.capacity() * (@sizeOf(AstId) + @sizeOf(SyntaxNode) + @sizeOf(u32));
    }

    pub fn get(m: *const AstIdMap, id: AstId) ?SyntaxNode {
        return m.map.get(id);
    }

    /// `item_tree` must have been built from the same syntax tree
    pub fn build(gpa: Allocator, item_tree: *const ItemTree, root: SyntaxNode) Allocator.Error!AstIdMap {
        var result: AstIdMap = .{};
        errdefer result.deinit(gpa);
        try result.map.ensureTotalCapacity(gpa, item_tree.items.len + item_tree.containers.len);
        // Same traversal order as Builder: number containers and members in order of appearance
        var c_index: u32 = 0;
        var i_index: u32 = 0;
        result.map.putAssumeCapacity(item_tree.containers[0].ast_id, root);
        c_index += 1;
        if (item_tree.items.len != 0 and item_tree.items[0].kind == .zon) {
            result.map.putAssumeCapacity(item_tree.items[0].ast_id, zonRoot(root).?);
            i_index += 1;
            walkNested(item_tree, root, &result, &c_index, &i_index);
        } else walk(item_tree, root, &result, &c_index, &i_index, 0);
        return result;
    }

    /// `container` is the index of the container `node`
    fn walk(item_tree: *const ItemTree, node: SyntaxNode, m: *AstIdMap, c_index: *u32, i_index: *u32, container: u32) void {
        var it = node.children();
        while (it.nextNode()) |member| {
            switch (member.kind()) {
                .fn_decl, .var_decl, .test_decl, .comptime_decl => {},
                .container_field => if (isUnderscoreMarker(member, item_tree.containers[container].kind)) continue,
                else => continue,
            }
            m.map.putAssumeCapacity(item_tree.items[i_index.*].ast_id, member);
            i_index.* += 1;
            walkNested(item_tree, member, m, c_index, i_index);
        }
    }

    fn walkNested(item_tree: *const ItemTree, node: SyntaxNode, m: *AstIdMap, c_index: *u32, i_index: *u32) void {
        var it = node.children();
        while (it.nextNode()) |c| {
            if (c.kind() != .container_decl) {
                walkNested(item_tree, c, m, c_index, i_index);
                continue;
            }
            const container = c_index.*;
            m.map.putAssumeCapacity(item_tree.containers[container].ast_id, c);
            c_index.* += 1;
            walk(item_tree, c, m, c_index, i_index, container);
        }
    }
};

