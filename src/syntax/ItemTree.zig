//! ItemTree: the declaration skeleton of a file.
//!
//! Records only "which containers exist, which members each container has, and each member's
//! name / kind / modifiers / signature hash / doc", with no position information and none of the
//! contents of function bodies or initializer expressions. Editing only a function body leaves
//! the ItemTree unchanged, so name resolution and signature type queries that depend on it are
//! not invalidated (early cutoff).
//!
//! Positions are looked up through `AstId` in `AstIdMap`. Containers defined inside function
//! bodies (such as the `struct {...}` returned by a generic type constructor) are included too,
//! since their members are part of name resolution.
//!
//! A ZON file has a single member: its root expression (kind `zon`, without a name), which owns
//! the Body that infers it.

const std = @import("std");
const Allocator = std.mem.Allocator;
const tree = @import("tree.zig");
const green = @import("green.zig");
const SyntaxNode = tree.SyntaxNode;
const SyntaxKind = @import("kind.zig").SyntaxKind;
const isTrivia = @import("kind.zig").isTrivia;
const ast = @import("ast.zig");
const Mode = @import("Parse.zig").Mode;

const ItemTree = @This();

arena: std.heap.ArenaAllocator.State,
/// Index 0 is the file itself
containers: []const Container,
items: []const Item,
/// Members of each container (indices into `items`), split by `Container.members`
member_list: []const u32,
/// The `//!` doc at the start of the file (with the `//!` prefix removed), lines joined with `\n`;
/// kept here so that showing it does not need the syntax tree of the file
file_doc: ?[]const u8,
/// Lookup tables derived from the fields above, so that `eql` and `fingerprint` do not compare
/// them: the items and the containers by AstId (AstIds are unique in a file), each entry
/// `AstId << 32 | index`, ascending
item_ids: []const u64,
container_ids: []const u64,
/// The named `fn` / `const` / `var` members of each container ordered by name, members with the
/// same name in member order; split by `decl_starts` (one more entry than `containers`)
decl_order: []const u32,
decl_starts: []const u32,
/// The containers each item declares (`Container.is_value` with that `parent_item`), in container
/// order; split by `value_starts` (one more entry than `items`)
value_containers: []const u32,
value_starts: []const u32,
/// Id of a parse result (`Parse.id`) whose syntax tree this tree was built from, or one with an
/// equal tree: `buildIncremental` copies the members whose top-level node that result shares with
/// a new one. Not compared by `eql`; may be advanced to a newer result that yields an equal tree
basis: std.atomic.Value(u64) = .init(0),

/// Node ID stable within the file: hashed from the parent node ID, kind, name, and ordinal among
/// same-named nodes; stays the same across edits as long as the node is not renamed or moved.
pub const AstId = enum(u32) { _ };

pub const Container = struct {
    ast_id: AstId,
    kind: Kind,
    /// The member that lexically contains this container (null for the file root)
    parent_item: ?u32,
    members: struct { start: u32, len: u32 },
    /// `packed` / `extern` (layout and ABI size computations read it instead of the syntax tree)
    layout: Layout = .auto,
    /// `union(enum)`: the tag type is generated by the compiler
    auto_enum: bool = false,
    /// The declaration has an argument: `enum(u8)`, `union(E)`, `packed struct(u32)`. Its value is
    /// in the body of the member that contains the container, not here
    has_arg: bool = false,
    /// An enum with a `_` member: non-exhaustive. `_` is not a field and has no item
    nonexhaustive: bool = false,
    /// The container is what `parent_item` declares: the initializer of a `const` / `var` member,
    /// the type of a field, or the operand of a `return` in a function member's body. Other
    /// containers in a member (local types, call arguments, `?struct {...}`, parameter types) are
    /// only lexically inside it
    is_value: bool = false,
    /// In the prototype of function `parent_item` (a parameter or return type) rather than in its
    /// body
    in_signature: bool = false,
    /// The name of the declaration (a member or a local constant) whose initializer is the
    /// container; null for anonymous containers and the file root
    name: ?[]const u8 = null,

    pub const Kind = enum { file, @"struct", @"enum", @"union", @"opaque" };
    pub const Layout = enum { auto, @"packed", @"extern" };
};

pub const Item = struct {
    ast_id: AstId,
    kind: Kind,
    /// Tuple fields, comptime blocks, anonymous tests, and the root expression of a ZON file have
    /// no name
    name: ?[]const u8,
    container: u32,
    flags: Flags,
    /// Structural hash of the signature part: function prototype, variable type annotation and
    /// alignment etc., field type; excludes function bodies and initializer expressions
    sig_hash: u64,
    /// Doc comment text (with the `///` prefix removed), lines joined with `\n`
    doc: ?[]const u8,

    /// `zon`: the root expression of a ZON file. It is not a declaration: it takes no part in the
    /// outline, symbol search, naming checks, or name resolution
    pub const Kind = enum { @"fn", @"const", @"var", field, @"test", @"comptime", zon };

    pub const Flags = packed struct(u16) {
        is_pub: bool = false,
        is_extern: bool = false,
        is_export: bool = false,
        is_inline: bool = false,
        is_noinline: bool = false,
        is_comptime: bool = false,
        is_threadlocal: bool = false,
        /// The function's return type is `!T` (inferred error set)
        inferred_error_set: bool = false,
        /// The function's parameter list has a non-binding parameter (`...`), only allowed last
        varargs: bool = false,
        padding: u7 = 0,
    };
};

pub fn deinit(self: *ItemTree, gpa: Allocator) void {
    var arena = self.arena.promote(gpa);
    arena.deinit();
    self.* = undefined;
}

/// A field may be just a name (enum members, void fields of unions), with the name in the
/// position of the type expression
pub fn bareFieldNames(kind: Container.Kind) bool {
    return kind == .@"enum" or kind == .@"union";
}

/// The index of the item with AstId `id`
pub fn itemOf(self: *const ItemTree, id: AstId) ?u32 {
    return findId(self.item_ids, id);
}

/// The index of the container with AstId `id`
pub fn containerOf(self: *const ItemTree, id: AstId) ?u32 {
    return findId(self.container_ids, id);
}

/// The lowest index with AstId `id` in `ids` (see `item_ids`)
fn findId(ids: []const u64, id: AstId) ?u32 {
    const key = @as(u64, @backingInt(id)) << 32;
    const i = std.sort.lowerBound(u64, ids, key, struct {
        fn order(k: u64, x: u64) std.math.Order {
            return std.math.order(k, x);
        }
    }.order);
    return if (i < ids.len and ids[i] >> 32 == @backingInt(id)) @truncate(ids[i]) else null;
}

fn sortedIds(a: Allocator, ids: anytype) Allocator.Error![]const u64 {
    const out = try a.alloc(u64, ids.len);
    for (ids, out, 0..) |x, *o, i| o.* = @as(u64, @backingInt(x.ast_id)) << 32 | i;
    std.sort.pdq(u64, out, {}, std.sort.asc(u64));
    return out;
}

/// The first `fn` / `const` / `var` member of `container` (in member order) named `name`
pub fn lookupDecl(self: *const ItemTree, container: u32, name: []const u8) ?u32 {
    const decls = self.decl_order[self.decl_starts[container]..self.decl_starts[container + 1]];
    const Ctx = struct {
        items: []const Item,
        name: []const u8,
        fn order(ctx: @This(), m: u32) std.math.Order {
            return std.mem.order(u8, ctx.name, ctx.items[m].name.?);
        }
    };
    const i = std.sort.lowerBound(u32, decls, Ctx{ .items = self.items, .name = name }, Ctx.order);
    if (i == decls.len or !std.mem.eql(u8, self.items[decls[i]].name.?, name)) return null;
    return decls[i];
}

/// The containers item `item` declares (see `Container.is_value`), in container order
pub fn valueContainers(self: *const ItemTree, item: u32) []const u32 {
    return self.value_containers[self.value_starts[item]..self.value_starts[item + 1]];
}

pub fn containerMembers(self: *const ItemTree, container: u32) []const u32 {
    const m = self.containers[container].members;
    return self.member_list[m.start..][0..m.len];
}

/// Whether the container declares a field; a file with top-level fields is a struct type, a file
/// without them is used as a namespace
pub fn hasFields(self: *const ItemTree, container: u32) bool {
    for (self.containerMembers(container)) |m| if (self.items[m].kind == .field) return true;
    return false;
}

pub fn eql(a: *const ItemTree, b: *const ItemTree) bool {
    if (a.containers.len != b.containers.len or a.items.len != b.items.len) return false;
    if (!std.mem.eql(u32, a.member_list, b.member_list)) return false;
    if (!optStrEql(a.file_doc, b.file_doc)) return false;
    for (a.containers, b.containers) |x, y| {
        if (x.ast_id != y.ast_id or x.kind != y.kind or x.parent_item != y.parent_item) return false;
        if (x.layout != y.layout or x.auto_enum != y.auto_enum or x.has_arg != y.has_arg or x.nonexhaustive != y.nonexhaustive or x.is_value != y.is_value or x.in_signature != y.in_signature) return false;
        if (!optStrEql(x.name, y.name)) return false;
        if (x.members.start != y.members.start or x.members.len != y.members.len) return false;
    }
    for (a.items, b.items) |x, y| {
        if (x.ast_id != y.ast_id or x.kind != y.kind or x.container != y.container) return false;
        if (@as(u16, @bitCast(x.flags)) != @as(u16, @bitCast(y.flags)) or x.sig_hash != y.sig_hash) return false;
        if (!optStrEql(x.name, y.name) or !optStrEql(x.doc, y.doc)) return false;
    }
    return true;
}

fn optStrEql(a: ?[]const u8, b: ?[]const u8) bool {
    if (a == null or b == null) return a == null and b == null;
    return std.mem.eql(u8, a.?, b.?);
}

/// A 128-bit hash of everything `eql` compares, in the same order, so that trees `eql` considers
/// equal have the same fingerprint. The engine keeps it for an evicted `FileItemTree`.
pub fn fingerprint(self: *const ItemTree) u128 {
    var h: Fingerprinter = .{ .sip = .init(&@splat(0)) };
    h.word(self.containers.len);
    h.word(self.items.len);
    h.word(self.member_list.len);
    h.sip.update(std.mem.sliceAsBytes(self.member_list));
    h.optStr(self.file_doc);
    for (self.containers) |c| {
        h.word(@backingInt(c.ast_id));
        h.word(@backingInt(c.kind));
        h.word(if (c.parent_item) |p| @as(u64, p) + 1 else 0);
        h.word(@backingInt(c.layout));
        h.word(@as(u64, @intFromBool(c.auto_enum)) | @as(u64, @intFromBool(c.has_arg)) << 1 |
            @as(u64, @intFromBool(c.nonexhaustive)) << 2 |
            @as(u64, @intFromBool(c.is_value)) << 3 | @as(u64, @intFromBool(c.in_signature)) << 4);
        h.optStr(c.name);
        h.word(c.members.start);
        h.word(c.members.len);
    }
    for (self.items) |it| {
        h.word(@backingInt(it.ast_id));
        h.word(@backingInt(it.kind));
        h.word(it.container);
        h.word(@as(u16, @bitCast(it.flags)));
        h.word(it.sig_hash);
        h.optStr(it.name);
        h.optStr(it.doc);
    }
    return h.sip.finalInt();
}

/// Every field is written as a fixed-size integer and strings with their length, so that
/// different sequences of fields cannot produce the same input bytes
const Fingerprinter = struct {
    sip: std.crypto.auth.siphash.SipHash128(1, 3),

    fn word(h: *Fingerprinter, v: u64) void {
        h.sip.update(std.mem.asBytes(&v));
    }

    fn optStr(h: *Fingerprinter, s: ?[]const u8) void {
        const str = s orelse return h.word(0);
        h.word(@as(u64, str.len) + 1);
        h.sip.update(str);
    }
};

// ── Build ────────────────────────────────────────────────────────────

/// The root expression of a ZON file (the only child of the root node that is not an error node)
pub fn zonRoot(root: SyntaxNode) ?SyntaxNode {
    var it = root.children();
    while (it.nextNode()) |n| if (n.kind() != .error_node) return n;
    return null;
}

pub fn build(gpa: Allocator, root: SyntaxNode, mode: Mode) Allocator.Error!ItemTree {
    return buildWith(gpa, root, mode, null);
}

/// The same tree as `build(gpa, root, .zig)`, copying from `prev` the members whose top-level node
/// is the same green node as in `old_root`, which `prev` was built from (or a tree that yields an
/// equal ItemTree): a member's items and containers depend only on its own subtree, and its
/// AstIds are assigned again in the same order as `build` assigns them
pub fn buildIncremental(gpa: Allocator, root: SyntaxNode, prev: *const ItemTree, old_root: SyntaxNode) Allocator.Error!ItemTree {
    var reuse = try Reuse.init(gpa, prev, old_root) orelse return build(gpa, root, .zig);
    defer reuse.deinit(gpa);
    return buildWith(gpa, root, .zig, &reuse);
}

/// The top-level members of `prev` by the green node they were built from, with the items and
/// containers each produced
const Reuse = struct {
    prev: *const ItemTree,
    by_node: std.AutoHashMapUnmanaged(*const green.GreenNode, u32) = .empty,
    /// Per top-level member: its item (the first of its range) and the end of its container
    /// range; the item ranges end at the next member's item
    tops: []const u32,
    container_ends: []const u32,

    fn init(gpa: Allocator, prev: *const ItemTree, old_root: SyntaxNode) Allocator.Error!?Reuse {
        var tops: std.ArrayList(u32) = .empty;
        errdefer tops.deinit(gpa);
        const item_top = try gpa.alloc(u32, prev.items.len);
        defer gpa.free(item_top);
        for (prev.items, item_top, 0..) |it, *t, i| {
            if (it.container == 0) {
                t.* = @intCast(tops.items.len);
                try tops.append(gpa, @intCast(i));
            } else t.* = item_top[prev.containers[it.container].parent_item.?];
        }
        const container_ends = try gpa.alloc(u32, tops.items.len);
        errdefer gpa.free(container_ends);
        @memset(container_ends, 1);
        // The containers of a member follow those of the members before it
        var last: u32 = 0;
        for (prev.containers[1..], 1..) |c, ci| {
            const top = item_top[c.parent_item.?];
            if (top < last) {
                gpa.free(container_ends);
                tops.deinit(gpa);
                return null;
            }
            last = top;
            container_ends[top] = @intCast(ci + 1);
        }
        for (1..@max(container_ends.len, 1)) |k| container_ends[k] = @max(container_ends[k], container_ends[k - 1]);
        var r: Reuse = .{ .prev = prev, .tops = try tops.toOwnedSlice(gpa), .container_ends = container_ends };
        errdefer r.deinit(gpa);
        var it = old_root.children();
        var k: u32 = 0;
        while (it.nextNode()) |member| {
            if (!isMemberKind(member.kind())) continue;
            if (k < r.tops.len) try r.by_node.put(gpa, member.green, k);
            k += 1;
        }
        // Each member node of the file is a top-level item; otherwise `prev` was not built from
        // this tree
        if (k != r.tops.len) {
            r.deinit(gpa);
            return null;
        }
        return r;
    }

    fn deinit(r: *Reuse, gpa: Allocator) void {
        r.by_node.deinit(gpa);
        gpa.free(r.tops);
        gpa.free(r.container_ends);
    }

    fn itemEnd(r: *const Reuse, k: u32) u32 {
        return if (k + 1 < r.tops.len) r.tops[k + 1] else @intCast(r.prev.items.len);
    }

    fn containerStart(r: *const Reuse, k: u32) u32 {
        return if (k == 0) 1 else r.container_ends[k - 1];
    }
};

pub fn isMemberKind(kind: SyntaxKind) bool {
    return switch (kind) {
        .fn_decl, .var_decl, .container_field, .test_decl, .comptime_decl => true,
        else => false,
    };
}

fn buildWith(gpa: Allocator, root: SyntaxNode, mode: Mode, reuse: ?*const Reuse) Allocator.Error!ItemTree {
    var arena: std.heap.ArenaAllocator = .init(gpa);
    errdefer arena.deinit();
    var b: Builder = .{ .gpa = gpa, .arena = arena.allocator(), .reuse = reuse };
    defer b.deinit();

    const file_id = mixId(0, "file", "", 0);
    try b.taken.put(gpa, file_id, {});
    try b.containers.append(gpa, .{ .ast_id = file_id, .kind = .file, .parent_item = null, .members = undefined });
    switch (mode) {
        .zig => try b.visitContainer(root, 0),
        .zon => try b.visitZonRoot(root),
    }

    // Lay out the member lists in container order
    var member_list: std.ArrayList(u32) = .empty;
    for (b.containers.items, b.pending_members.items) |*c, members| {
        c.members = .{ .start = @intCast(member_list.items.len), .len = @intCast(members.items.len) };
        try member_list.appendSlice(b.arena, members.items);
    }
    const containers = try b.arena.dupe(Container, b.containers.items);
    const items = try b.arena.dupe(Item, b.items.items);
    const file_doc = try docLines(b.arena, root, .container_doc_comment);

    var decl_order: std.ArrayList(u32) = .empty;
    const decl_starts = try b.arena.alloc(u32, containers.len + 1);
    for (containers, 0..) |c, ci| {
        decl_starts[ci] = @intCast(decl_order.items.len);
        const start = decl_order.items.len;
        for (member_list.items[c.members.start..][0..c.members.len]) |m| switch (items[m].kind) {
            .@"fn", .@"const", .@"var" => if (items[m].name != null) try decl_order.append(b.arena, m),
            else => {},
        };
        // The item indices of a container's members increase in member order
        std.sort.pdq(u32, decl_order.items[start..], items, struct {
            fn lt(its: []const Item, x: u32, y: u32) bool {
                return switch (std.mem.order(u8, its[x].name.?, its[y].name.?)) {
                    .lt => true,
                    .gt => false,
                    .eq => x < y,
                };
            }
        }.lt);
    }
    decl_starts[containers.len] = @intCast(decl_order.items.len);
    // Counting sort of the value containers by parent item, keeping container order
    const value_starts = try b.arena.alloc(u32, items.len + 1);
    @memset(value_starts, 0);
    for (containers) |c| if (c.is_value) if (c.parent_item) |p| {
        value_starts[p + 1] += 1;
    };
    for (1..value_starts.len) |i| value_starts[i] += value_starts[i - 1];
    const value_containers = try b.arena.alloc(u32, value_starts[items.len]);
    const fill = try b.gpa.dupe(u32, value_starts[0..items.len]);
    defer b.gpa.free(fill);
    for (containers, 0..) |c, ci| if (c.is_value) if (c.parent_item) |p| {
        value_containers[fill[p]] = @intCast(ci);
        fill[p] += 1;
    };
    const item_ids = try sortedIds(b.arena, items);
    const container_ids = try sortedIds(b.arena, containers);
    // Everything is allocated before the arena state is copied
    return .{
        .arena = arena.state,
        .containers = containers,
        .items = items,
        .member_list = member_list.items,
        .file_doc = file_doc,
        .item_ids = item_ids,
        .container_ids = container_ids,
        .decl_order = decl_order.items,
        .decl_starts = decl_starts,
        .value_containers = value_containers,
        .value_starts = value_starts,
    };
}

const Builder = struct {
    gpa: Allocator,
    arena: Allocator,
    containers: std.ArrayList(Container) = .empty,
    /// One-to-one with `containers`; collects each container's members during the build
    pending_members: std.ArrayList(std.ArrayList(u32)) = .empty,
    items: std.ArrayList(Item) = .empty,
    taken: std.AutoHashMapUnmanaged(AstId, void) = .empty,
    /// Visiting the prototype of a function member (see `Container.in_signature`)
    in_signature: bool = false,
    /// Members to copy instead of visiting (top-level members only)
    reuse: ?*const Reuse = null,

    fn deinit(b: *Builder) void {
        b.containers.deinit(b.gpa);
        b.pending_members.deinit(b.gpa);
        b.items.deinit(b.gpa);
        b.taken.deinit(b.gpa);
    }

    /// `node` is a source_file or container_decl; `index` is its already registered container index
    fn visitContainer(b: *Builder, node: SyntaxNode, index: u32) Allocator.Error!void {
        while (b.pending_members.items.len <= index) try b.pending_members.append(b.gpa, .empty);
        const container_id = b.containers.items[index].ast_id;
        var it = node.children();
        while (it.nextNode()) |member| {
            if (index == 0) if (b.reuse) |r| if (r.by_node.get(member.green)) |k| {
                try b.copyMember(r, k);
                continue;
            };
            const kind: Item.Kind = switch (member.kind()) {
                .fn_decl => .@"fn",
                .var_decl => if (member.childToken(.keyword_var) != null) .@"var" else .@"const",
                .container_field => if (isUnderscoreMarker(member, b.containers.items[index].kind)) {
                    b.containers.items[index].nonexhaustive = true;
                    continue;
                } else .field,
                .test_decl => .@"test",
                .comptime_decl => .@"comptime",
                else => continue,
            };
            const name = if (ast.memberName(member, bareFieldNames(b.containers.items[index].kind))) |t| try ast.identNameAlloc(b.arena, t.text) else null;
            const item_index: u32 = @intCast(b.items.items.len);
            try b.items.append(b.gpa, .{
                .ast_id = try b.uniqueId(container_id, @tagName(kind), name orelse ""),
                .kind = kind,
                .name = if (name) |n| try b.arena.dupe(u8, n) else null,
                .container = index,
                .flags = fnFlags(member, memberFlags(member)),
                .sig_hash = signatureHash(member, kind),
                .doc = try b.docText(member),
            });
            try b.pending_members.items[index].append(b.arena, item_index);
            try b.visitNested(member, item_index, valueOffset(member));
        }
    }

    /// Appends the items and containers of top-level member `k` of `r.prev` in the order
    /// `visitContainer` creates them, assigning their AstIds in that order
    fn copyMember(b: *Builder, r: *const Reuse, k: u32) Allocator.Error!void {
        const span: Span = .{
            .item_start = r.tops[k],
            .item_base = @intCast(b.items.items.len),
            .container_start = r.containerStart(k),
            .container_end = r.container_ends[k],
            .container_base = @intCast(b.containers.items.len),
        };
        try b.copyItem(r.prev, span, r.tops[k]);
        std.debug.assert(b.items.items.len - span.item_base == r.itemEnd(k) - r.tops[k]);
        std.debug.assert(b.containers.items.len - span.container_base == span.container_end - span.container_start);
    }

    /// Old and new index bases of the items and containers of a copied member
    const Span = struct {
        item_start: u32,
        item_base: u32,
        container_start: u32,
        container_end: u32,
        container_base: u32,

        fn item(s: Span, old: u32) u32 {
            return old - s.item_start + s.item_base;
        }

        fn container(s: Span, old: u32) u32 {
            return if (old == 0) 0 else old - s.container_start + s.container_base;
        }
    };

    fn copyItem(b: *Builder, prev: *const ItemTree, span: Span, old: u32) Allocator.Error!void {
        const it = prev.items[old];
        const container = span.container(it.container);
        const item_index: u32 = @intCast(b.items.items.len);
        std.debug.assert(item_index == span.item(old));
        try b.items.append(b.gpa, .{
            .ast_id = try b.uniqueId(b.containers.items[container].ast_id, @tagName(it.kind), it.name orelse ""),
            .kind = it.kind,
            .name = if (it.name) |n| try b.arena.dupe(u8, n) else null,
            .container = container,
            .flags = it.flags,
            .sig_hash = it.sig_hash,
            .doc = if (it.doc) |d| try b.arena.dupe(u8, d) else null,
        });
        try b.pending_members.items[container].append(b.arena, item_index);
        // The containers lexically in the item, in the order `visitNested` finds them
        for (prev.containers[span.container_start..span.container_end], span.container_start..) |c, ci| {
            if (c.parent_item == old) try b.copyContainer(prev, span, @intCast(ci));
        }
    }

    fn copyContainer(b: *Builder, prev: *const ItemTree, span: Span, old: u32) Allocator.Error!void {
        var c = prev.containers[old];
        const index: u32 = @intCast(b.containers.items.len);
        std.debug.assert(index == span.container(old));
        const parent = span.item(c.parent_item.?);
        c.ast_id = try b.uniqueId(b.items.items[parent].ast_id, "container", "");
        c.parent_item = parent;
        c.members = undefined;
        if (c.name) |n| c.name = try b.arena.dupe(u8, n);
        try b.containers.append(b.gpa, c);
        while (b.pending_members.items.len <= index) try b.pending_members.append(b.gpa, .empty);
        for (prev.containerMembers(old)) |m| try b.copyItem(prev, span, m);
    }

    /// A ZON file: the root expression is the only member of the file; container definitions inside
    /// it (not part of ZON, but parsable) are collected as usual
    fn visitZonRoot(b: *Builder, root: SyntaxNode) Allocator.Error!void {
        try b.pending_members.append(b.gpa, .empty);
        if (zonRoot(root) == null) return;
        const item_index: u32 = @intCast(b.items.items.len);
        try b.items.append(b.gpa, .{
            .ast_id = try b.uniqueId(b.containers.items[0].ast_id, "zon", ""),
            .kind = .zon,
            .name = null,
            .container = 0,
            .flags = .{},
            .sig_hash = 0,
            .doc = null,
        });
        try b.pending_members.items[0].append(b.arena, item_index);
        try b.visitNested(root, item_index, null);
    }

    /// Finds container definitions in a member's subtree (including inside function bodies),
    /// without descending into containers already found. `value` is the offset of the container
    /// that is the member's initializer or field type (see `valueOffset`)
    fn visitNested(b: *Builder, node: SyntaxNode, parent_item: u32, value: ?u32) Allocator.Error!void {
        if (!node.green.flags.has_container) return;
        var it = node.children();
        while (it.nextNode()) |c| {
            if (c.kind() != .container_decl) {
                const outer = b.in_signature;
                defer b.in_signature = outer;
                if (node.kind() == .fn_decl and c.kind() == .fn_proto) b.in_signature = true;
                try b.visitNested(c, parent_item, value);
                continue;
            }
            const index: u32 = @intCast(b.containers.items.len);
            const kind = containerKind(c);
            const bound = if (node.kind() == .var_decl) bound: {
                const decl: ast.VarDecl = .{ .syntax = node };
                const init = decl.initExpr() orelse break :bound null;
                if (init.offset != c.offset) break :bound null;
                const name = decl.name() orelse break :bound null;
                break :bound try b.arena.dupe(u8, try ast.identNameAlloc(b.arena, name.text));
            } else null;
            try b.containers.append(b.gpa, .{
                .ast_id = try b.uniqueId(b.items.items[parent_item].ast_id, "container", ""),
                .kind = kind,
                .parent_item = parent_item,
                .members = undefined,
                .layout = if (c.childToken(.keyword_packed) != null) .@"packed" else if (c.childToken(.keyword_extern) != null) .@"extern" else .auto,
                .auto_enum = kind == .@"union" and c.childToken(.keyword_enum) != null,
                .has_arg = (ast.ContainerDecl{ .syntax = c }).argExpr() != null,
                .is_value = value == c.offset or (node.kind() == .return_expr and b.items.items[parent_item].kind == .@"fn"),
                .in_signature = b.in_signature,
                .name = bound,
            });
            const outer = b.in_signature;
            defer b.in_signature = outer;
            b.in_signature = false;
            try b.visitContainer(c, index);
        }
    }

    /// Offset of the container that a member declares directly: the initializer of a `const` /
    /// `var` or the type of a field, when it is a container definition
    fn valueOffset(member: SyntaxNode) ?u32 {
        const value = switch (member.kind()) {
            .var_decl => (ast.VarDecl{ .syntax = member }).initExpr(),
            .container_field => (ast.ContainerField{ .syntax = member }).typeExpr(),
            else => null,
        } orelse return null;
        return if (value.kind() == .container_decl) value.offset else null;
    }

    /// The n-th node with the same (kind, name) under the same parent
    fn uniqueId(b: *Builder, parent: AstId, kind: []const u8, name: []const u8) Allocator.Error!AstId {
        var ordinal: u32 = 0;
        while (true) : (ordinal += 1) {
            const id = mixId(@backingInt(parent), kind, name, ordinal);
            if (!(try b.taken.getOrPut(b.gpa, id)).found_existing) return id;
        }
    }

    fn docText(b: *Builder, member: SyntaxNode) Allocator.Error!?[]const u8 {
        return docLines(b.arena, member, .doc_comment);
    }
};

/// The doc comments of `kind` (`///` or `//!`, both three bytes long) among the leading tokens of
/// `node`, before its first token that is neither trivia nor such a comment: one line each, with
/// the prefix, one following space, and a trailing `\r` removed, joined with `\n`; null when
/// there are none
fn docLines(arena: Allocator, node: SyntaxNode, kind: SyntaxKind) Allocator.Error!?[]const u8 {
    var out: std.ArrayList(u8) = .empty;
    var it = node.children();
    while (it.next()) |e| {
        if (e != .token) break;
        if (e.token.kind != kind) {
            if (isTrivia(e.token.kind)) continue;
            break;
        }
        var line = e.token.text["///".len..];
        if (std.mem.startsWith(u8, line, " ")) line = line[1..];
        if (out.items.len != 0) try out.append(arena, '\n');
        try out.appendSlice(arena, std.mem.trimEnd(u8, line, "\r"));
    }
    return if (out.items.len == 0) null else out.items;
}

fn mixId(parent: u32, kind: []const u8, name: []const u8, ordinal: u32) AstId {
    var h: std.hash.Wyhash = .init(parent);
    h.update(kind);
    h.update(&.{0});
    h.update(name);
    h.update(std.mem.asBytes(&ordinal));
    return @fromBackingInt(@as(u32, @truncate(h.final())));
}

/// The bare `_` member of an enum, which marks it as non-exhaustive (`@"_"` is an ordinary field)
fn isUnderscoreMarker(member: SyntaxNode, container: Container.Kind) bool {
    if (container != .@"enum") return false;
    const name = ast.memberName(member, true) orelse return false;
    return std.mem.eql(u8, name.text, "_");
}

/// Syntactic information from the function prototype needed downstream (keeps signature
/// inference from reading the syntax tree, which changes on every edit)
fn fnFlags(member: SyntaxNode, base: Item.Flags) Item.Flags {
    var flags = base;
    const proto = (ast.cast(ast.FnDecl, member) orelse return flags).proto() orelse return flags;
    flags.inferred_error_set = proto.inferredErrorSet();
    var it = proto.params();
    while (it.next()) |p| {
        const param = ast.cast(ast.Param, p).?;
        if (param.name() == null and param.typeExpr() == null) flags.varargs = true;
    }
    return flags;
}

fn memberFlags(member: SyntaxNode) Item.Flags {
    var flags: Item.Flags = .{};
    var it = member.children();
    while (it.next()) |e| {
        if (e != .token) {
            if (e.node.kind() == .fn_proto) continue;
            break;
        }
        switch (e.token.kind) {
            .keyword_pub => flags.is_pub = true,
            .keyword_extern => flags.is_extern = true,
            .keyword_export => flags.is_export = true,
            .keyword_inline => flags.is_inline = true,
            .keyword_noinline => flags.is_noinline = true,
            .keyword_comptime => flags.is_comptime = true,
            .keyword_threadlocal => flags.is_threadlocal = true,
            .keyword_const, .keyword_var, .identifier, .keyword_fn => break,
            else => {},
        }
    }
    return flags;
}

fn containerKind(node: SyntaxNode) Container.Kind {
    var it = node.children();
    while (it.next()) |e| switch (e.kind()) {
        .keyword_struct => return .@"struct",
        .keyword_enum => return .@"enum",
        .keyword_union => return .@"union",
        .keyword_opaque => return .@"opaque",
        else => {},
    };
    return .@"struct";
}

/// Signature hash: hashes the non-trivia tokens (kind and text) of the signature part;
/// for a container definition only its head counts.
fn signatureHash(member: SyntaxNode, kind: Item.Kind) u64 {
    var h: std.hash.Wyhash = .init(0);
    switch (kind) {
        .@"fn" => if (member.childNode(.fn_proto)) |proto| hashTokens(&h, proto),
        .@"const", .@"var" => {
            // After the name and before `=`: type annotation and align / addrspace / linksection
            var it = member.children();
            var seen_name = false;
            while (it.next()) |e| {
                if (e == .token) {
                    if (e.token.kind == .equal) break;
                    if (e.token.kind == .identifier) seen_name = true;
                    if (seen_name and !isTrivia(e.token.kind)) hashToken(&h, e.token);
                } else if (seen_name) hashTokens(&h, e.node);
            }
            // When initialized with a container definition, include its head (kind, arguments);
            // the members are recorded separately
            if (initContainer(member)) |c| hashContainerHead(&h, c);
        },
        .field => {
            var it = member.children();
            while (it.next()) |e| {
                if (e == .token) {
                    if (e.token.kind == .equal) break;
                    if (!isTrivia(e.token.kind) and e.token.kind != .doc_comment) hashToken(&h, e.token);
                } else if (e.node.kind() == .container_decl) {
                    hashContainerHead(&h, e.node);
                } else hashTokens(&h, e.node);
            }
        },
        .@"test", .@"comptime", .zon => {},
    }
    return h.final();
}

fn initContainer(member: SyntaxNode) ?SyntaxNode {
    var it = member.children();
    var after_equal = false;
    while (it.next()) |e| {
        if (e == .token and e.token.kind == .equal) after_equal = true;
        if (after_equal and e == .node) return if (e.node.kind() == .container_decl) e.node else null;
    }
    return null;
}

fn hashContainerHead(h: *std.hash.Wyhash, node: SyntaxNode) void {
    var it = node.children();
    while (it.next()) |e| {
        if (e == .token) {
            if (e.token.kind == .l_brace) break;
            if (!isTrivia(e.token.kind)) hashToken(h, e.token);
        } else hashTokens(h, e.node);
    }
}

fn hashToken(h: *std.hash.Wyhash, t: tree.SyntaxToken) void {
    h.update(std.mem.asBytes(&t.kind));
    h.update(t.text);
}

fn hashTokens(h: *std.hash.Wyhash, node: SyntaxNode) void {
    var it = node.children();
    while (it.next()) |e| switch (e) {
        .token => |t| if (!isTrivia(t.kind)) hashToken(h, t),
        .node => |c| hashTokens(h, c),
    };
}

// ── AstId → node ─────────────────────────────────────────────────────

/// Mapping from AstId to node in one parse result. Rebuilt after every reparse; maps stable IDs
/// back to nodes in the current tree.
pub const AstIdMap = struct {
    map: std.AutoHashMapUnmanaged(AstId, SyntaxNode) = .empty,
    /// The nodes by item and container index of the ItemTree the map was built with
    items: []const SyntaxNode = &.{},
    containers: []const SyntaxNode = &.{},
    /// Per top-level member of a Zig file, in order: the end of its item and container ranges
    /// (empty for a ZON file)
    top_item_ends: []const u32 = &.{},
    top_container_ends: []const u32 = &.{},

    pub fn deinit(m: *AstIdMap, gpa: Allocator) void {
        m.map.deinit(gpa);
        gpa.free(m.items);
        gpa.free(m.containers);
        gpa.free(m.top_item_ends);
        gpa.free(m.top_container_ends);
    }

    /// Bytes used by the tables (the nodes belong to the syntax tree and are not counted)
    pub fn bytes(m: *const AstIdMap) usize {
        return m.map.capacity() * (@sizeOf(AstId) + @sizeOf(SyntaxNode) + @sizeOf(u32)) +
            (m.items.len + m.containers.len) * @sizeOf(SyntaxNode) + (m.top_item_ends.len + m.top_container_ends.len) * @sizeOf(u32);
    }

    pub fn get(m: *const AstIdMap, id: AstId) ?SyntaxNode {
        return m.map.get(id);
    }

    /// `item_tree` must have been built from the same syntax tree
    pub fn build(gpa: Allocator, item_tree: *const ItemTree, root: SyntaxNode) Allocator.Error!AstIdMap {
        return buildMap(gpa, item_tree, root, null);
    }

    /// The same map as `build`, shifting the nodes of `prev` for the top-level members whose
    /// node is the same green node as in the tree `prev` was built from: the items and
    /// containers of a member are found in its own subtree. The tree of `prev` must still be
    /// alive, so that equal pointers mean the same node
    pub fn buildIncremental(gpa: Allocator, item_tree: *const ItemTree, root: SyntaxNode, prev: *const AstIdMap) Allocator.Error!AstIdMap {
        if (item_tree.items.len != 0 and item_tree.items[0].kind == .zon) return AstIdMap.build(gpa, item_tree, root);
        var by_node: std.AutoHashMapUnmanaged(*const green.GreenNode, u32) = .empty;
        defer by_node.deinit(gpa);
        try by_node.ensureTotalCapacity(gpa, @intCast(prev.top_item_ends.len));
        var start: u32 = 0;
        for (prev.top_item_ends, 0..) |end, k| {
            by_node.putAssumeCapacity(prev.items[start].green, @intCast(k));
            start = end;
        }
        return buildMap(gpa, item_tree, root, .{ .prev = prev, .by_node = &by_node });
    }

    const Reused = struct {
        prev: *const AstIdMap,
        by_node: *const std.AutoHashMapUnmanaged(*const green.GreenNode, u32),
    };

    const Walker = struct {
        item_tree: *const ItemTree,
        items: []SyntaxNode,
        containers: []SyntaxNode,
        c_index: u32 = 0,
        i_index: u32 = 0,
        top_item_ends: std.ArrayList(u32) = .empty,
        top_container_ends: std.ArrayList(u32) = .empty,
        reused: ?Reused,
    };

    fn buildMap(gpa: Allocator, item_tree: *const ItemTree, root: SyntaxNode, reused: ?Reused) Allocator.Error!AstIdMap {
        var w: Walker = .{
            .item_tree = item_tree,
            .items = try gpa.alloc(SyntaxNode, item_tree.items.len),
            .containers = undefined,
            .reused = reused,
        };
        defer w.top_item_ends.deinit(gpa);
        defer w.top_container_ends.deinit(gpa);
        errdefer gpa.free(w.items);
        w.containers = try gpa.alloc(SyntaxNode, item_tree.containers.len);
        errdefer gpa.free(w.containers);
        // Same traversal order as Builder: number containers and members in order of appearance
        w.containers[0] = root;
        w.c_index = 1;
        // One entry per top-level member at most
        const tops = root.green.children.len;
        try w.top_item_ends.ensureTotalCapacity(gpa, tops);
        try w.top_container_ends.ensureTotalCapacity(gpa, tops);
        if (item_tree.items.len != 0 and item_tree.items[0].kind == .zon) {
            w.items[0] = zonRoot(root).?;
            w.i_index = 1;
            walkNested(&w, root);
        } else walk(&w, root, 0);
        std.debug.assert(w.i_index == w.items.len and w.c_index == w.containers.len);

        var result: AstIdMap = .{ .items = w.items, .containers = w.containers };
        errdefer {
            result.map.deinit(gpa);
            gpa.free(result.top_item_ends);
        }
        try result.map.ensureTotalCapacity(gpa, @intCast(item_tree.items.len + item_tree.containers.len));
        for (item_tree.containers, w.containers) |c, n| result.map.putAssumeCapacity(c.ast_id, n);
        for (item_tree.items, w.items) |it, n| result.map.putAssumeCapacity(it.ast_id, n);
        result.top_item_ends = try w.top_item_ends.toOwnedSlice(gpa);
        result.top_container_ends = try w.top_container_ends.toOwnedSlice(gpa);
        return result;
    }

    /// `container` is the index of the container `node`
    fn walk(w: *Walker, node: SyntaxNode, container: u32) void {
        var it = node.children();
        while (it.nextNode()) |member| {
            switch (member.kind()) {
                .fn_decl, .var_decl, .test_decl, .comptime_decl => {},
                .container_field => if (isUnderscoreMarker(member, w.item_tree.containers[container].kind)) continue,
                else => continue,
            }
            if (container == 0) if (w.reused) |r| if (r.by_node.get(member.green)) |k| {
                const prev = r.prev;
                const item_start = if (k == 0) 0 else prev.top_item_ends[k - 1];
                const container_start = if (k == 0) 1 else prev.top_container_ends[k - 1];
                const old_items = prev.items[item_start..prev.top_item_ends[k]];
                const old_containers = prev.containers[container_start..prev.top_container_ends[k]];
                // Both nodes are the same green node: everything in it moves by the same amount
                const old_offset = prev.items[item_start].offset;
                for (old_items, w.items[w.i_index..][0..old_items.len]) |o, *n| n.* = .{ .green = o.green, .offset = o.offset - old_offset + member.offset };
                for (old_containers, w.containers[w.c_index..][0..old_containers.len]) |o, *n| n.* = .{ .green = o.green, .offset = o.offset - old_offset + member.offset };
                w.i_index += @intCast(old_items.len);
                w.c_index += @intCast(old_containers.len);
                w.top_item_ends.appendAssumeCapacity(w.i_index);
                w.top_container_ends.appendAssumeCapacity(w.c_index);
                continue;
            };
            w.items[w.i_index] = member;
            w.i_index += 1;
            walkNested(w, member);
            if (container == 0) {
                w.top_item_ends.appendAssumeCapacity(w.i_index);
                w.top_container_ends.appendAssumeCapacity(w.c_index);
            }
        }
    }

    fn walkNested(w: *Walker, node: SyntaxNode) void {
        if (!node.green.flags.has_container) return;
        var it = node.children();
        while (it.nextNode()) |c| {
            if (c.kind() != .container_decl) {
                walkNested(w, c);
                continue;
            }
            const container = w.c_index;
            w.containers[container] = c;
            w.c_index += 1;
            walk(w, c, container);
        }
    }
};

